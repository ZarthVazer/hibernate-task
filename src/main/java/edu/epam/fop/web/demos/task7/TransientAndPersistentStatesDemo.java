package edu.epam.fop.web.demos.task7;

import edu.epam.fop.web.jpa.HibernateUtil;
import edu.epam.fop.web.jpa.entity.Course;
import edu.epam.fop.web.jpa.repository.CourseRepository;
import org.hibernate.Session;
import org.hibernate.SessionFactory;
import org.hibernate.Transaction;

/**
 * Shows how a Course goes from the transient state to the persistent state.
 * <p>
 * Transient: the object is created with {@code new}. It has no id, there is no row
 * for it in the database and no Session knows about it.
 * <p>
 * Persistent: after {@code session.persist()} the object belongs to the Session
 * (persistence context). It gets an id, a row is inserted, and any change made to
 * the object is saved automatically when the transaction is committed.
 *
 * @author Adilov Abdubosit
 */
public class TransientAndPersistentStatesDemo {

    public static void main(String[] args) {
        SessionFactory sessionFactory = HibernateUtil.getSessionFactory();
        Long id = null;
        try (Session session = sessionFactory.openSession()) {
            // Transient state: plain Java object, id is null and the session does not contain it
            Course course = new Course("Transient course");
            System.out.println("Transient: id = " + course.getId() + ", contains = " + session.contains(course));

            Transaction transaction = session.beginTransaction();

            // Persistent state: persist() attaches the object to the session.
            // The id is generated by the database (bigserial), so Hibernate runs the INSERT
            // immediately and the id is available right after this call.
            session.persist(course);
            System.out.println("Persistent: id = " + course.getId() + ", contains = " + session.contains(course));

            // We do not call any update method here. Hibernate compares the object with the
            // state it loaded (dirty checking) and runs an UPDATE on commit by itself.
            course.setName("Persistent course");
            transaction.commit();
            id = course.getId();

            // While the session is open the object stays persistent. session.get() does not
            // go to the database, it returns the same instance from the first-level cache.
            Course sameCourse = session.get(Course.class, id);
            System.out.println("Same instance: " + (sameCourse == course) + ", " + sameCourse);
        } finally {
            // Remove the test course so the demo can be run many times
            if (id != null) {
                new CourseRepository().delete(id);
            }
            HibernateUtil.shutdown();
        }
    }
}
